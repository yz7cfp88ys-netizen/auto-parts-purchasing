CREATE TABLE IF NOT EXISTS ams_schema_versions (
 version INT PRIMARY KEY, applied_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ams_categories (
 id CHAR(36) PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ams_products (
 id CHAR(36) PRIMARY KEY, sku VARCHAR(80) NOT NULL UNIQUE,
 name VARCHAR(200) NOT NULL, category_id CHAR(36) NOT NULL,
 vehicle_type VARCHAR(10) NOT NULL, description TEXT NOT NULL,
 specifications TEXT NOT NULL, image_url VARCHAR(2000) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, version INT NOT NULL DEFAULT 1,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 FOREIGN KEY (category_id) REFERENCES ams_categories(id), INDEX (active, category_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ams_inquiries (
 id CHAR(36) PRIMARY KEY, reference VARCHAR(40) NOT NULL UNIQUE,
 request_id CHAR(36) NOT NULL UNIQUE, payload_hash CHAR(64) NOT NULL,
 contact_name VARCHAR(100) NOT NULL, email VARCHAR(200) NOT NULL,
 company VARCHAR(160) NOT NULL, country VARCHAR(100) NOT NULL,
 phone VARCHAR(80) NOT NULL, business VARCHAR(100) NOT NULL,
 order_type VARCHAR(100) NOT NULL, notes TEXT NOT NULL, services TEXT NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'new', admin_notes TEXT NOT NULL,
 version INT NOT NULL DEFAULT 1, locale VARCHAR(10) NOT NULL DEFAULT 'en',
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 INDEX (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ams_inquiry_items (
 id CHAR(36) PRIMARY KEY, inquiry_id CHAR(36) NOT NULL, position INT NOT NULL,
 product_id CHAR(36) NULL, sku_snapshot VARCHAR(80) NOT NULL,
 description VARCHAR(300) NOT NULL, specifications TEXT NOT NULL, quantity INT NOT NULL,
 FOREIGN KEY (inquiry_id) REFERENCES ams_inquiries(id),
 FOREIGN KEY (product_id) REFERENCES ams_products(id), INDEX (inquiry_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ams_inquiry_events (
 id CHAR(36) PRIMARY KEY, inquiry_id CHAR(36) NOT NULL, actor VARCHAR(200) NOT NULL,
 status VARCHAR(30) NOT NULL, notes TEXT NOT NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY (inquiry_id) REFERENCES ams_inquiries(id), INDEX (inquiry_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ams_outbox (
 id CHAR(36) PRIMARY KEY, inquiry_id CHAR(36) NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL DEFAULT 'pending', attempts INT NOT NULL DEFAULT 0,
 next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 lease_token CHAR(36) NULL, last_error VARCHAR(100) NOT NULL DEFAULT '',
 sent_at DATETIME(3) NULL, created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY (inquiry_id) REFERENCES ams_inquiries(id), INDEX (status, next_attempt_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ams_sessions (
 token_hash CHAR(64) PRIMARY KEY, csrf CHAR(64) NOT NULL,
 admin_email VARCHAR(200) NOT NULL, credential_hash CHAR(64) NOT NULL,
 expires_at DATETIME(3) NOT NULL, INDEX (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
